/**
 * Best image for a subject: exact subject match first, then the first tag overlap.
 * Venue photos are only used for their own subjects, never as a generic tag match —
 * a photo of one specific place shouldn't stand in for somewhere else.
 */
export function imageFor(subject: string, tags: string[] = []): EditorialImageMeta | null {
  const exact = IMAGES.find((i) => i.subjects.includes(subject));
  if (exact) return exact;
  const lower = tags.map((t) => t.toLowerCase());
  return IMAGES.find((i) => i.kind === 'illustrative' && i.tags.some((t) => lower.some((l) => l.includes(t.toLowerCase())))) ?? null;
}
